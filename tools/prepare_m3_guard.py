"""Recover constant tables and the scalar M3 detector from the ARM oracle.

The desktop caller uses mode=1 only. The mode=0 colour/rim branches belong to
other filters and are deliberately excluded. Keep this reproducible translation
beside the original Ghidra listing for auditing operation order and thresholds.
"""
from pathlib import Path
import hashlib
import re
import struct
from elftools.elf.elffile import ELFFile

root = Path(__file__).resolve().parents[1]
library = root/'lib/arm64-v8a/libzxicamodelembed.so'
assert hashlib.sha256(library.read_bytes()).hexdigest()=='a3b66074a9a17671f957abb7bcebe9a70fd6431f69c317e308859fda3be6419e', 'Unexpected ARM oracle'
with library.open('rb') as f:
    elf = ELFFile(f)
    segments = [(s['p_vaddr'], s.data()) for s in elf.iter_segments() if s['p_type']=='PT_LOAD']

def read(address, size):
    address -= 0x100000  # Ghidra image base
    return next(data[address-base:address-base+size] for base,data in segments
                if base <= address and address+size <= base+len(data))

tables = []
for name,address,count,kind in [('decode',0x55d800,4097,'f'),('encode',0x561804,16385,'f'),
    ('grade_x',0x55d7b8,9,'f'),('grade_y',0x55d7dc,9,'f'),
    ('DAT_00571808',0x571808,8,'i'),('DAT_00571828',0x571828,8,'i'),
    ('DAT_00571848',0x571848,6,'i'),('DAT_0057184c',0x57184c,6,'i'),
    ('DAT_00571850',0x571850,6,'i'),('DAT_00100a40',0x100a40,2,'i'),
    ('DAT_00100b40',0x100b40,2,'i')]:
    values = struct.unpack('<'+str(count)+kind,read(address,count*4))
    strings = [float(v).hex()+'f' if kind=='f' else str(v) for v in values]
    tables.append('static const '+('float' if kind=='f' else 'int')+' '+name+'[] = {\n'+
                  ',\n'.join(','.join(strings[i:i+8]) for i in range(0,len(strings),8))+'\n};\n')
(root/'tools/m3_guard_tables.h').write_text('/* ARM constants SHA256 '+hashlib.sha256(library.read_bytes()).hexdigest()+' */\n'+''.join(tables),'utf-8')

# The ARM math helper uses musl's log2f/exp2f with double FMA. The Windows
# CRT implementations have different rounding, so retain the helper's tables.
with (root/'assets/math_arm.elf').open('rb') as f:
    elf=ELFFile(f)
    math_segments=[(s['p_vaddr'],s.data()) for s in elf.iter_segments() if s['p_type']=='PT_LOAD']
    symbols={s.name:s['st_value'] for s in elf.get_section_by_name('.symtab').iter_symbols()}
def math_read(name,size):
    address=symbols[name]
    return next(data[address-base:address-base+size] for base,data in math_segments if base<=address<base+len(data))
values=struct.unpack('<36d',math_read('__log2f_data',288))
exp_data=math_read('__exp2f_data',288)
math_tables='static const double m3_log_data[] = {'+','.join(float(v).hex() for v in values)+'};\n'
math_tables+='static const uint64_t m3_exp_tab[] = {'+','.join(hex(v)+'ULL' for v in struct.unpack('<32Q',exp_data[:256]))+'};\n'
math_tables+='static const double m3_exp_data[] = {'+','.join(float(v).hex() for v in struct.unpack('<4d',exp_data[256:]))+'};\n'
(root/'tools/m3_math_tables.h').write_text('/* Constants from the bundled musl ARM math helper. */\n'+math_tables,'utf-8')

source=(root/'research/native_guard.c').read_text('utf-8')
detector=source[source.index('void detect_rows('):source.index('/* 00580c48')]
start=detector.index('if (iVar7 == 0) {')
opening=detector.index('{',start)
depth=1; end=opening+1
while depth:
    depth += (detector[end]=='{')-(detector[end]=='}');end+=1
assert re.match(r'\s*else\s*{\s*fVar62 = 0.6;\s*}',detector[end:])
tail=re.match(r'\s*else\s*{\s*fVar62 = 0.6;\s*}',detector[end:]).end()
detector=detector[:start]+'fVar62 = 0.6;'+detector[end+tail:]
# Ghidra flattens this multiplication tree. Restore the ARM instruction
# grouping at 0x4808a8..0x4808dc instead of reassociating six float factors.
detector,count=re.subn(r'fVar68 = \(1\.0 - fVar63[\s\S]*?;',
    '''fVar68 = ((1.0 - fVar60 * fVar60 * (3.0 - (fVar60 + fVar60))) *
                  (fVar54 * (1.0 - fVar63 * fVar63 * (3.0 - (fVar63 + fVar63))))) *
                 (fVar62 * fVar71) * fVar68;''',detector)
assert count==1
detector,count=re.subn(r'fVar62 = fVar62 \* fVar61 \* fVar61 \* \(3\.0 - \(fVar61 \+ fVar61\)\);',
    'fVar62 = fVar62 * ((fVar61 * fVar61) * (3.0 - (fVar61 + fVar61)));',detector)
assert count==1
detector=detector.replace('NEON_ucvtf','')
assert 'NEON_' not in detector
detector=re.sub(r'\bundefined8\b','uint64_t',detector)
detector=re.sub(r'\blong\b','intptr_t',detector)
detector=re.sub(r'\bulong\b','uintptr_t',detector)
detector=re.sub(r'\(&?(DAT_[0-9a-f]+)\)',r'\1',detector)
detector=re.sub(r'(?<![\w.])(\d+\.\d*(?:e[+-]?\d+)?)(?![\w.])',r'\1f',detector)
(root/'tools/m3_guard_detector.h').write_text('/* Recovered scalar mode=1 detector; generated by prepare_m3_guard.py. */\n'+detector,'utf-8')
print('Recovered M3 tables and scalar detector')
